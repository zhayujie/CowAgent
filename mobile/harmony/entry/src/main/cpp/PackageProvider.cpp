#include "RNOH/PackageProvider.h"
#include "RNOHPackagesFactory.h"
#include "CowNativePackage.h"
#include "generated/RNOHGeneratedPackage.h"
#include "ReanimatedPackage.h"
#include "ReanimatedWorkletPackage.h"
#include "RnohReactNativeHarmonyGestureHandlerPackage.h"
#include "RnohReactNativeHarmonyScreensPackage.h"
#include "SVGPackage.h"

using namespace rnoh;

std::vector<std::shared_ptr<Package>> PackageProvider::getPackages(
    Package::Context ctx) {
  auto packages = createRNOHPackages(ctx); // <= autolinking
  packages.push_back(std::make_shared<RNOHGeneratedPackage>(
      ctx)); // generated by codegen-harmony v1 on app preBuilt stage)
  // Not covered by autolinking; see ets/PackageProvider.ets.
  packages.push_back(
      std::make_shared<RnohReactNativeHarmonyGestureHandlerPackage>(ctx));
  packages.push_back(std::make_shared<ReanimatedWorkletPackage>(ctx));
  packages.push_back(std::make_shared<ReanimatedPackage>(ctx));
  packages.push_back(std::make_shared<RnohReactNativeHarmonyScreensPackage>(ctx));
  packages.push_back(std::make_shared<SVGPackage>(ctx));
  packages.push_back(std::make_shared<CowNativePackage>(ctx));
  return packages;
}
