"""Trusted IM identity and Markdown profiles. Never infer identity from message text."""
import hashlib
import json
import threading
from pathlib import Path

from common import i18n

_PROFILE_LOCK = threading.RLock()
FEISHU_IMAGE_DIRECTORY = ".feishu-images"


def _key(*parts):
    return hashlib.sha256(json.dumps(parts, ensure_ascii=False).encode()).hexdigest()[:32]


def feishu_group_memory_scope(app_id, chat_id):
    return "feishu-group-" + _key(app_id, chat_id)


def feishu_identity(msg, *, owner_open_ids=(), private_memory_mode="owner_workspace"):
    """Build identity only from a channel-created message, not a model argument."""
    sender = getattr(msg, "actual_user_id", None) or getattr(msg, "from_user_id", "") or ""
    app = getattr(msg, "identity_app_id", "") or getattr(msg, "to_user_id", "") or ""
    tenant = getattr(msg, "identity_tenant_key", "") or ""
    group = bool(getattr(msg, "is_group", False))
    chat = getattr(msg, "other_user_id", "") if group else ""
    valid = bool(sender and app and (chat or not group))
    human = getattr(msg, "identity_sender_type", "user") == "user"
    owner = valid and human and sender in owner_open_ids
    person = _key("feishu", app, tenant, sender) if valid else "unknown"
    # A group can have members from different tenants. Its chat ID is stable
    # across speakers, while the sender's tenant remains part of their profile.
    scope = feishu_group_memory_scope(app, chat) if group else "feishu-user-" + person
    if not valid:
        scope = "feishu-unknown-" + _key(app, tenant, chat, getattr(msg, "msg_id", ""))
    return dict(channel="feishu", app_id=app, tenant_key=tenant, sender_id=sender,
                display_name=getattr(msg, "actual_user_nickname", "") or "",
                group_id=chat, message_id=getattr(msg, "msg_id", "") or "",
                is_group=group, is_owner=owner, valid=valid, person_key=person,
                memory_scope=scope,
                legacy_private=valid and human and not group and (
                    private_memory_mode == "shared" or (private_memory_mode == "owner_workspace" and owner)
                ))


def private_session_id(msg, instance_id):
    identity = feishu_identity(
        msg, owner_open_ids=getattr(msg, "identity_owner_open_ids", ()),
        private_memory_mode=getattr(msg, "identity_private_memory_mode", "owner_workspace"),
    )
    access = "workspace" if identity["legacy_private"] else "personal"
    key = _key(instance_id, identity["app_id"], identity["tenant_key"], identity["memory_scope"], access)
    return f"feishu-private-{key}"


def feishu_session_id(msg, instance_id, share_group):
    if not msg.is_group:
        return private_session_id(msg, instance_id)
    if share_group:
        return msg.other_user_id
    return f"{msg.from_user_id}:{msg.other_user_id}"


def feishu_image_dir(msg, instance_id, share_group):
    session_id = feishu_session_id(msg, instance_id, share_group)
    # A shared group session can contain senders from multiple tenants.
    tenant_key = "" if msg.is_group and share_group else msg.identity_tenant_key
    key = _key(instance_id, msg.identity_app_id, tenant_key, session_id)
    return _feishu_image_root() / key


def _feishu_image_root():
    from common import state_dir

    # Image events can precede a question and its Agent route. The tools
    # recognize this directory by conversation even when the speaker changes.
    return state_dir.shared_root().resolve() / "tmp" / FEISHU_IMAGE_DIRECTORY


def attributed_query(query, identity):
    """The outer label is generated by the backend; body and names remain untrusted."""
    label = {k: identity[k] for k in ("channel", "app_id", "sender_id", "group_id", "message_id", "display_name")}
    return "[平台记录的发言人 " + json.dumps(label, ensure_ascii=False) + "]\n" + query


def profile_path(workspace, identity):
    if not identity["valid"]:
        raise ValueError("Missing platform identity; profile access disabled")
    if identity["legacy_private"]:
        raise ValueError("This direct chat uses the workspace USER.md")
    context = "group-" + _key(identity["group_id"]) if identity["is_group"] else "private"
    root = Path(workspace).resolve()
    path = root / "people" / "feishu" / _key(identity["app_id"], identity["tenant_key"]) / identity["person_key"] / context / "USER.md"
    # Reject symlink/junction escapes as well as lexical traversal.
    resolved_path = path.resolve()
    if resolved_path != root and root not in resolved_path.parents:
        raise ValueError("Profile path outside workspace")
    return path


def read_profile(workspace, identity):
    with _PROFILE_LOCK:
        path = profile_path(workspace, identity)
        return path.read_text(encoding="utf-8")[:12000] if path.is_file() else ""


