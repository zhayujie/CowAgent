def attach_identity(agent, identity, *, image_dir=None):
    """Called each turn; tools are session-local and context is replaced, not accumulated."""
    from agent.tools.memory.feishu_member_profile import FeishuMemberProfileTool
    agent._sender_identity = identity
    scoped = bool(identity and not identity["legacy_private"])
    agent._current_user_id = identity["memory_scope"] if scoped else None
    agent.tools = [t for t in agent.tools if t.name != "member_profile"]
    for tool in agent.tools:
        tool.feishu_restricted = bool(identity and (scoped or not identity["is_owner"]))
        if tool.name in {"read", "write", "edit", "send", "vision", "ls", "memory_get"}:
            tool.feishu_memory_scope = (agent.workspace_dir, agent._current_user_id) if identity and agent.workspace_dir else None
            tool.feishu_image_dir = image_dir if identity else None
        if tool.name == "memory_search":
            tool.user_id = agent._current_user_id
            tool.include_shared = not scoped
            tool.include_knowledge = scoped
        elif tool.name == "memory_get":
            tool.allowed_memory_scope = agent._current_user_id
    if scoped and identity["valid"] and agent.workspace_dir:
        agent.tools.append(FeishuMemberProfileTool(agent.workspace_dir, identity))


def memory_path_denial(tool, path):
    """Return a denial reason after resolving aliases, including junctions and symlinks."""
    local_path = Path(path).absolute()
    # Inspect both paths so neither an alias into the directory nor an image
    # symlink pointing outside it can inherit the conversation's permission.
    target = local_path.resolve()
    if any(part.casefold() == FEISHU_IMAGE_DIRECTORY for part in (*local_path.parts, *target.parts)):
        image_root = _feishu_image_root()
        if any(item == image_root or image_root in item.parents for item in (local_path, target)):
            image_dir = getattr(tool, "feishu_image_dir", None)
            if (image_dir and target.parent == image_dir and target.suffix == ".png"
                    and tool.name in {"read", "send", "vision"}):
                return None
            return "Feishu image outside current conversation"

    scope = getattr(tool, "feishu_memory_scope", None)
    if scope is None:
        return None
    workspace, user_id = scope
    root = Path(workspace).resolve()
    knowledge_tools = {"read", "ls", "memory_get", "write", "edit"}
    in_knowledge = False
    if tool.name in knowledge_tools:
        from agent.tools.utils.memory_path import selected_knowledge_root

        knowledge = selected_knowledge_root(root)
        in_knowledge = knowledge is not None and (target == knowledge or knowledge in target.parents)
        for entry in (root / "knowledge", knowledge):
            if entry is not None and (local_path == entry or entry in local_path.parents) and not in_knowledge:
                return "path escapes the selected knowledge base"

    protected = ["people", "memory/long-term", "agents/team.json"]
    if user_id:
        protected.extend(("USER.md", "MEMORY.md", "BOOTSTRAP.md", "memory"))
    else:
        protected.append("memory/users")
    for name in protected:
        boundary = (root / name).resolve()
        if target == boundary or boundary in target.parents:
            if name == "memory" and user_id:
                personal = root / "memory" / "users" / user_id
                if personal.resolve() == personal and (target == personal or personal in target.parents):
                    return None
            return "private memory path"
    if getattr(tool, "feishu_restricted", False):
        allowed = [root]
        if getattr(tool, "cwd", None):
            allowed.append(Path(tool.cwd).resolve())
        if not in_knowledge and not any(base == target or base in target.parents for base in allowed):
            return "path outside Feishu workspace and project directory"
        if target.name.casefold() in {"team.json", "config.json"}:
            return "protected Feishu configuration path"
        if "agents" in target.parts[len(root.parts):] and root in target.parents:
            return "path inside another Agent workspace"
    return None
