export type Lang = 'en'

// The app ships English-only now; the old OS-locale detection is gone.
// currentLang stays a module-level variable so setLang()/getLang() and every
// t() call site keep working unchanged.
let currentLang: Lang = 'en'

export function t(key: string): string {
  return translations[currentLang]?.[key] || translations['en']?.[key] || key
}

export function getLang(): Lang {
  return currentLang
}

export function setLang(lang: Lang) {
  currentLang = lang
  localStorage.setItem('cow_lang', lang)
}

/** Resolve a possibly-localized label ({zh,en} or plain string) for the current language. */
export function localizedLabel(label: string | { zh: string; en: string } | undefined): string {
  if (!label) return ''
  if (typeof label === 'string') return label
  return label[currentLang] || label.en || label.zh || ''
}
